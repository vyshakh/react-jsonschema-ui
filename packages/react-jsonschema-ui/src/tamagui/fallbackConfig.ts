let fallback: ReturnType<typeof createFallbackConfig> | undefined;

function createFallbackConfig() {
  return createTamagui({
    tokens,
    themes,
    fonts: { body, heading: body },
    settings: { defaultFont: 'body', shouldAddPrefersColorThemes: true, fastSchemeChange: true },
  });
}

/**
 * The config for a `<TamaguiProvider>` that `<SchemaForm>` renders itself when
 * it is not inside one: the app's own if it called createTamagui, the
 * built-in fallback otherwise.
 */
export function getProviderConfig() {
  try {
    return getConfig();
  } catch {
    // createTamagui has not run.
  }
  fallback ??= createFallbackConfig();
  return fallback;
}
